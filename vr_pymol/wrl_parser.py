"""Split a PyMOL-exported VRML2 (.wrl) scene into batchable primitives.

`vtkVRMLImporter` creates one vtkActor per VRML node, and profiling showed
its `Update()` call itself (not file size, not PyMOL's export time) is the
bottleneck: ~70s for 4hhb cartoon+sticks, which exports 8782 individual
`Transform{ children Shape{...} }` nodes (one per bond/atom sphere).

Checked directly against real pymol-open-source exports (every representation
on 1CRN): only three geometry kinds ever appear --
  - `Sphere`, always wrapped as `Transform { translation T  children Shape {
    geometry Sphere { radius R } appearance ... material Material {
    diffuseColor R G B ... } } }` (no `rotation` field -- spheres are
    orientation-independent).
  - `Cylinder`, same shape but with an added `rotation AX AY AZ ANGLE` field
    on the Transform, and `children [ Shape { ... } ]` (bracketed list, vs.
    the bare single child for spheres) -- both forms are handled here.
  - `IndexedFaceSet`, PyMOL's one baked mesh for cartoon/surface -- never
    numerous (one or a few per scene), so it isn't the bottleneck and is left
    for `vtkVRMLImporter` to parse as before.

This parser extracts every Sphere/Cylinder Transform block's numeric fields
directly via regex (the file is machine-generated by a single writer with
consistent formatting) and returns everything else verbatim as "leftover"
VRML text for the caller to still hand to `vtkVRMLImporter`. Any Transform
block that doesn't cleanly match the expected single-sphere/single-cylinder
shape (unexpected future PyMOL export changes) is conservatively routed to
leftover instead of guessed at, so worst case this only loses the perf win,
never produces wrong geometry.
"""

import math
import re

_FLOAT = r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?"
_TRANSLATION_RE = re.compile(
    rf"translation\s+({_FLOAT})\s+({_FLOAT})\s+({_FLOAT})"
)
_ROTATION_RE = re.compile(
    rf"rotation\s+({_FLOAT})\s+({_FLOAT})\s+({_FLOAT})\s+({_FLOAT})"
)
_SPHERE_RADIUS_RE = re.compile(rf"geometry Sphere \{{\s*radius\s+({_FLOAT})")
_CYLINDER_RE = re.compile(
    rf"geometry Cylinder \{{\s*radius\s+({_FLOAT})\s+height\s+({_FLOAT})"
)
_DIFFUSE_COLOR_RE = re.compile(
    rf"diffuseColor\s+({_FLOAT})\s+({_FLOAT})\s+({_FLOAT})"
)


def _split_top_level_blocks(text):
    """Yield each top-level `Name { ... }` block, matched by brace depth.

    Top-level blocks are back-to-back separated only by whitespace (no VRML
    content lives between them), so each block simply runs from where the
    previous one ended to where this one's closing brace returns to depth 0.
    Square brackets (used for VRML's `[ ... ]` list fields, e.g. `point [`)
    don't affect this -- only curly braces nest node bodies.
    """
    depth = 0
    block_start = 0
    for i, ch in enumerate(text):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                yield text[block_start : i + 1]
                block_start = i + 1


def _parse_sphere(block):
    t = _TRANSLATION_RE.search(block)
    r = _SPHERE_RADIUS_RE.search(block)
    c = _DIFFUSE_COLOR_RE.search(block)
    if not (t and r and c):
        return None
    return {
        "center": tuple(float(v) for v in t.groups()),
        "radius": float(r.group(1)),
        "color": tuple(float(v) for v in c.groups()),
    }


def _parse_cylinder(block):
    t = _TRANSLATION_RE.search(block)
    rot = _ROTATION_RE.search(block)
    cyl = _CYLINDER_RE.search(block)
    c = _DIFFUSE_COLOR_RE.search(block)
    if not (t and rot and cyl and c):
        return None
    ax, ay, az, angle = (float(v) for v in rot.groups())
    return {
        "center": tuple(float(v) for v in t.groups()),
        "axis": (ax, ay, az),
        "angle_deg": math.degrees(angle),
        "radius": float(cyl.group(1)),
        "height": float(cyl.group(2)),
        "color": tuple(float(v) for v in c.groups()),
    }


def parse_wrl(path):
    """Return `(spheres, cylinders, leftover_text)` for the .wrl at `path`.

    `spheres`/`cylinders` are lists of plain dicts (see `_parse_sphere`/
    `_parse_cylinder`). `leftover_text` is everything else, unchanged and
    still a valid standalone VRML2 file.
    """
    with open(path, "r") as f:
        text = f.read()

    header_end = text.find("\n", text.index("#VRML"))
    header = text[: header_end + 1]
    body = text[header_end + 1 :]

    spheres = []
    cylinders = []
    leftover_chunks = [header]

    for block in _split_top_level_blocks(body):
        is_transform = block.lstrip().startswith("Transform")
        has_sphere = "geometry Sphere" in block
        has_cylinder = "geometry Cylinder" in block

        parsed = None
        if is_transform and has_sphere and not has_cylinder:
            parsed = _parse_sphere(block)
            if parsed is not None:
                spheres.append(parsed)
        elif is_transform and has_cylinder and not has_sphere:
            parsed = _parse_cylinder(block)
            if parsed is not None:
                cylinders.append(parsed)

        if parsed is None:
            leftover_chunks.append(block)

    return spheres, cylinders, "\n".join(leftover_chunks)
